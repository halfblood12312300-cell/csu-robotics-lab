  '首先，我们在这里所谈论的机器人开发特指软件开发，即怎么在现有的机器人平台上实现智能化。比如让机器人完成一次导览，取个外卖，或者买杯咖啡。

这对于人来说当然是极其简单的事情，但对于机器人而言，却需要考虑几个方面的问题：一个是硬件上能不能完成所需要的动作，另一个是软件上能不能实现具体的任务。硬件不是我们现阶段考虑的重点，我们更关心的是，怎么让一个已经具备相应运动能力的机器人知道自己该做什么。

我们所说的软件，实际上在很大程度上相当于机器人的大脑。说起大脑，大语言模型自然能引起很多人的兴趣。大语言模型已经表现出了相当强的泛化能力，如果能直接把它作为机器人的大脑，那自然是一劳永逸的事情。但仔细一想，就会发现其中的难点：大语言模型怎么理解机器人自身的状态，又怎么理解机器人所处环境的状态？

虽然大语言模型已经在很多领域展现了它的威力，但毕竟不是仙术，它本质上还是在生成一连串的 Token。比如我们现在让机器人向前运动一米，大语言模型应该怎么做？显然，直接输出一句“向前运动一米”，机器人是不会听懂的，这中间就需要一层翻译。

既然机器人是由计算机控制的，那么我们只需要写一个让机器人向前运动一米的程序，再让它执行这个程序就行了。但这个程序怎么写呢？像宇树机器人，开发过程中往往会涉及 ROS 和厂商提供的 SDK。如果大语言模型不了解这些接口，显然也很难写出正确的程序。那我们就需要让它具备检索资料的能力，甚至可以直接在它的 Memory 里写上一些提示，告诉它去哪个网站找开发文档，或者告诉它以前遇到类似问题时是怎么解决的。再让它具备调用工具和执行程序的能力，这实际上就已经是一个 Agent 了。

那么，假如我们最终写完了向前运动一米的程序，机器人也成功运行了这个程序，大语言模型怎么知道任务真的完成了呢？程序运行结束和机器人确实向前运动了一米，显然不是一回事。我们还需要写一个反馈程序，通过里程计、计算机视觉、激光雷达等获取机器人当前的状态，再把这些信息反馈给大语言模型。

这样，向前运动一米的问题就初步解决了。但如果下一次我们让机器人向前运动两米呢？是否还需要重新走一遍刚才的流程，去官网查找资料，再写一遍代码？

显然没有这个必要。我们完全可以复用之前写好的程序，甚至在一开始写程序的时候，就把运动距离作为一个参数留出来。我们还可以进一步推广这种方法，创建一系列的程序母本，或者说功能模块。这样，大语言模型想要控制机器人的具体运动，只需要选择对应的模块，再给定相应的参数就行了。如果这些模块足够丰富，我们就有可能用一连串的指令把一个复杂的任务拼出来。

当然，如果我们要实现自动化，就不能每次都由人告诉大语言模型该走一米还是两米，而是要让它自己知道应该走多远。那么它又是怎么知道这一点的呢？

比如我让机器人去买杯咖啡，而机器人现在还在实验室里，那它首先就要走出实验室。怎么出去呢？首先要知道门在哪里。雷达能够告诉机器人周围障碍物的距离和分布，而要知道某个地方是不是门，则可以借助计算机视觉。但如果机器人在起始位置根本看不到门呢？显然，我们不能让大语言模型自己乱猜。我们可以事先告诉它一条走出实验室的路线，也可以借助已有的地图和定位导航功能，让它知道自己在哪里、应该往哪里走。

一个看起来极其简单的任务，拆解下来其实已经涉及不少问题了。

那么，一个更核心的问题紧接着就浮现出来了。假如我们要完成的任务特别复杂，中间可能涉及几十个步骤，而大语言模型每调用一次指令都需要花费一定的时间进行思考，那么整个任务的时间成本可能会变得相当可怕。

怎么做可以有效降低这一时间成本呢？

既然反复调用大语言模型需要花费不少时间，那我们不妨想办法减少它需要思考的次数。比如我们可以把走出实验室的整个过程封装成一个模块，这样，大语言模型只需要决定调用这个模块，而不需要分别思考什么时候前进、什么时候转弯、什么时候停下来。这显然可以降低整个任务的时间成本。

但这又带来了一个问题。我们想要实现的是机器人的智能化，而这样一个高度封装的模块更像是一个提前写好的脚本，似乎并没有那么智能。如果换了一个实验室，甚至只是实验室里的桌椅摆放发生了变化，这个模块还能不能用呢？

这个问题实际上就和搭积木一样。小的积木只需要几种，就可以拼出各种各样的形状，但拼接的过程可能会很漫长。而如果我们使用一些已经拼好的大积木，拼出一个完整形状所需要的步骤自然就少了，但要想拼出更多的形状，无非是需要多准备几种大积木罢了。

那么，我们是不是可以在两者之间找到一个合适的平衡？保留一些足够通用的基础模块，同时也针对一些常见的任务，开发粒度更大的功能模块。这样既不至于让大语言模型每次都从最基础的动作开始思考，也保留了模块之间重新组合的可能性。

实际上，从工程应用的角度来说，我们现阶段追求的未必是某种完全意义上的智能，而是机器人在实际任务中所表现出来的智能。如果我们提出的绝大多数任务，机器人都能够在没有人为干预的情况下自主完成，那么它究竟是通过大语言模型一步一步思考出来的，还是通过调用一系列提前开发好的功能模块实现的，似乎也就没有那么重要了。

这实际上就把我们具体的开发任务分成了两块：一个是 Agent 的构建，即怎么让大语言模型理解任务，并合理地使用我们已经创建的模块；另一个是具体功能模块的开发，即怎么让机器人具备完成各种任务所需要的能力。

至于这些模块应该做得多大，需要开发多少种模块，以及 Agent 应该怎么去组合和调用它们，这些都是值得我们在实际开发过程中不断探索的问题。

